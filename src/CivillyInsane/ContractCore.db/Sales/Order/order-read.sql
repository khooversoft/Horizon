CREATE VIEW [AppDbo].[order-read]
AS
SELECT  t.[order_id]
        ,t.[customer_id]
        ,t.[email]
        ,t.[status]
        ,t.[currency_code]
        ,t.[subtotal_cents]
        ,t.[shipping_cents]
        ,t.[tax_cents]
        ,t.[discount_cents]
        ,t.[total_cents]
        ,t.[ship_name]
        ,t.[ship_line1]
        ,t.[ship_line2]
        ,t.[ship_city]
        ,t.[ship_region]
        ,t.[ship_postal_code]
        ,t.[ship_country_code]
        ,t.[placed_utc]
        ,t.[created_utc]
        ,t.[modified_utc]
        ,t.[JsonData]
FROM    [AppDbo].[order] t;
