CREATE TABLE [AppDbo].[SalesOrderItem]
(
    [RowId] bigint IDENTITY(1,1) NOT NULL,
    [SalesOrderItemId] nvarchar(50) NOT NULL,
    [SalesOrderRowId] bigint NOT NULL,
    [ProductIdSnapshot] nvarchar(50) NOT NULL,
    [ProductVariantIdSnapshot] nvarchar(50) NOT NULL,
    [SkuSnapshot] nvarchar(75) NOT NULL,
    [ProductNameSnapshot] nvarchar(250) NOT NULL,
    [VariantNameSnapshot] nvarchar(200) NOT NULL,
    [ProviderSkuSnapshot] nvarchar(100) NULL,
    [FulfillmentProviderCodeSnapshot] nvarchar(50) NULL,
    [Quantity] int NOT NULL,
    [UnitListPrice] decimal(19,4) NOT NULL,
    [UnitSalePrice] decimal(19,4) NOT NULL,
    [DiscountAmount] decimal(19,4) NOT NULL CONSTRAINT [DF_SalesOrderItem_DiscountAmount] DEFAULT (0),
    [TaxAmount] decimal(19,4) NOT NULL CONSTRAINT [DF_SalesOrderItem_TaxAmount] DEFAULT (0),
    [LineTotal] decimal(19,4) NOT NULL,
    [CreatedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_SalesOrderItem_CreatedUtc] DEFAULT (SYSUTCDATETIME()),
    [JsonData] varchar(max) NULL,
    CONSTRAINT [PK_SalesOrderItem] PRIMARY KEY CLUSTERED ([RowId]),
    CONSTRAINT [UQ_SalesOrderItem_SalesOrderItemId] UNIQUE NONCLUSTERED ([SalesOrderItemId]),
    CONSTRAINT [CK_SalesOrderItem_BusinessId] CHECK (LEN(TRIM([SalesOrderItemId])) > 0),
    CONSTRAINT [CK_SalesOrderItem_JsonData] CHECK ([JsonData] IS NULL OR ISJSON([JsonData]) = 1),
    CONSTRAINT [FK_SalesOrderItem_SalesOrderRowId] FOREIGN KEY ([SalesOrderRowId]) REFERENCES [AppDbo].[SalesOrder] ([RowId]),
    CONSTRAINT [CK_SalesOrderItem_Rule1] CHECK (Quantity > 0),
    CONSTRAINT [CK_SalesOrderItem_Rule2] CHECK (UnitListPrice >= 0 AND UnitSalePrice >= 0 AND DiscountAmount >= 0 AND TaxAmount >= 0 AND LineTotal >= 0),
    CONSTRAINT [CK_SalesOrderItem_Rule3] CHECK (LineTotal = Quantity * UnitSalePrice + TaxAmount),
    CONSTRAINT [CK_SalesOrderItem_Rule4] CHECK (DiscountAmount = Quantity * (UnitListPrice - UnitSalePrice))
);
