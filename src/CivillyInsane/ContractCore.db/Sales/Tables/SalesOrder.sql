CREATE TABLE [AppDbo].[SalesOrder]
(
    [RowId] bigint IDENTITY(1,1) NOT NULL,
    [SalesOrderId] nvarchar(50) NOT NULL,
    [OrderNumber] nvarchar(50) NOT NULL,
    [SiteRowId] bigint NOT NULL,
    [CustomerRowId] bigint NULL,
    [SourceCartRowId] bigint NULL,
    [SourceSubscriptionRowId] bigint NULL,
    [CustomerEmail] nvarchar(320) NOT NULL,
    [CurrencyCode] char(3) NOT NULL,
    [OrderStatusCode] varchar(25) NOT NULL CONSTRAINT [DF_SalesOrder_OrderStatusCode] DEFAULT ('pending-payment'),
    [PaymentStatusCode] varchar(25) NOT NULL CONSTRAINT [DF_SalesOrder_PaymentStatusCode] DEFAULT ('pending'),
    [FulfillmentStatusCode] varchar(25) NOT NULL CONSTRAINT [DF_SalesOrder_FulfillmentStatusCode] DEFAULT ('not-submitted'),
    [ItemSubtotal] decimal(19,4) NOT NULL,
    [DiscountTotal] decimal(19,4) NOT NULL CONSTRAINT [DF_SalesOrder_DiscountTotal] DEFAULT (0),
    [ShippingTotal] decimal(19,4) NOT NULL CONSTRAINT [DF_SalesOrder_ShippingTotal] DEFAULT (0),
    [TaxTotal] decimal(19,4) NOT NULL CONSTRAINT [DF_SalesOrder_TaxTotal] DEFAULT (0),
    [GrandTotal] decimal(19,4) NOT NULL,
    [PlacedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_SalesOrder_PlacedUtc] DEFAULT (SYSUTCDATETIME()),
    [IdempotencyKey] nvarchar(100) NOT NULL,
    [ScheduledProcessUtc] datetime2(3) NULL,
    [RenewalResultCode] varchar(20) NULL,
    [CreatedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_SalesOrder_CreatedUtc] DEFAULT (SYSUTCDATETIME()),
    [ModifiedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_SalesOrder_ModifiedUtc] DEFAULT (SYSUTCDATETIME()),
    [RowVersion] rowversion NOT NULL,
    [JsonData] varchar(max) NULL,
    CONSTRAINT [PK_SalesOrder] PRIMARY KEY CLUSTERED ([RowId]),
    CONSTRAINT [UQ_SalesOrder_SalesOrderId] UNIQUE NONCLUSTERED ([SalesOrderId]),
    CONSTRAINT [CK_SalesOrder_BusinessId] CHECK (LEN(TRIM([SalesOrderId])) > 0),
    CONSTRAINT [CK_SalesOrder_JsonData] CHECK ([JsonData] IS NULL OR ISJSON([JsonData]) = 1),
    CONSTRAINT [FK_SalesOrder_SiteRowId] FOREIGN KEY ([SiteRowId]) REFERENCES [AppDbo].[Site] ([RowId]),
    CONSTRAINT [FK_SalesOrder_CustomerRowId] FOREIGN KEY ([CustomerRowId]) REFERENCES [AppDbo].[Customer] ([RowId]),
    CONSTRAINT [FK_SalesOrder_SourceCartRowId] FOREIGN KEY ([SourceCartRowId]) REFERENCES [AppDbo].[Cart] ([RowId]),
    CONSTRAINT [FK_SalesOrder_SourceSubscriptionRowId] FOREIGN KEY ([SourceSubscriptionRowId]) REFERENCES [AppDbo].[Subscription] ([RowId]),
    CONSTRAINT [FK_SalesOrder_CurrencyCode] FOREIGN KEY ([CurrencyCode]) REFERENCES [AppDbo].[Currency] ([CurrencyCode]),
    CONSTRAINT [CK_SalesOrder_Rule1] CHECK (OrderStatusCode IN ('pending-payment','paid','submitted','processing','shipped','complete','cancelled')),
    CONSTRAINT [CK_SalesOrder_Rule2] CHECK (PaymentStatusCode IN ('pending','requires-action','authorized','paid','partially-refunded','refunded','failed','voided','disputed')),
    CONSTRAINT [CK_SalesOrder_Rule3] CHECK (FulfillmentStatusCode IN ('not-submitted','submitted','accepted','processing','shipped','delivered','cancelled','failed')),
    CONSTRAINT [CK_SalesOrder_Rule4] CHECK (ItemSubtotal >= 0 AND DiscountTotal >= 0 AND DiscountTotal <= ItemSubtotal AND ShippingTotal >= 0 AND TaxTotal >= 0 AND GrandTotal >= 0),
    CONSTRAINT [CK_SalesOrder_Rule5] CHECK (GrandTotal = ItemSubtotal - DiscountTotal + ShippingTotal + TaxTotal),
    CONSTRAINT [CK_SalesOrder_Rule6] CHECK (RenewalResultCode IS NULL OR RenewalResultCode IN ('succeeded','failed')),
    CONSTRAINT [CK_SalesOrder_Rule7] CHECK ((SourceSubscriptionRowId IS NULL AND ScheduledProcessUtc IS NULL) OR (SourceSubscriptionRowId IS NOT NULL AND ScheduledProcessUtc IS NOT NULL))
);
