CREATE TABLE [AppDbo].[PaymentTransaction]
(
    [RowId] bigint IDENTITY(1,1) NOT NULL,
    [PaymentTransactionId] nvarchar(50) NOT NULL,
    [PaymentRowId] bigint NOT NULL,
    [ProviderCode] nvarchar(50) NOT NULL,
    [TransactionTypeCode] varchar(25) NOT NULL,
    [ProviderTransactionId] nvarchar(200) NULL,
    [ProviderEventId] nvarchar(200) NULL,
    [Amount] decimal(19,4) NOT NULL,
    [CurrencyCode] char(3) NOT NULL,
    [StatusCode] varchar(20) NOT NULL,
    [FailureCode] nvarchar(100) NULL,
    [FailureMessage] nvarchar(1000) NULL,
    [OccurredUtc] datetime2(3) NOT NULL,
    [CreatedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_PaymentTransaction_CreatedUtc] DEFAULT (SYSUTCDATETIME()),
    [JsonData] varchar(max) NULL,
    CONSTRAINT [PK_PaymentTransaction] PRIMARY KEY CLUSTERED ([RowId]),
    CONSTRAINT [UQ_PaymentTransaction_PaymentTransactionId] UNIQUE NONCLUSTERED ([PaymentTransactionId]),
    CONSTRAINT [CK_PaymentTransaction_BusinessId] CHECK (LEN(TRIM([PaymentTransactionId])) > 0),
    CONSTRAINT [CK_PaymentTransaction_JsonData] CHECK ([JsonData] IS NULL OR ISJSON([JsonData]) = 1),
    CONSTRAINT [FK_PaymentTransaction_PaymentRowId] FOREIGN KEY ([PaymentRowId]) REFERENCES [AppDbo].[Payment] ([RowId]),
    CONSTRAINT [FK_PaymentTransaction_CurrencyCode] FOREIGN KEY ([CurrencyCode]) REFERENCES [AppDbo].[Currency] ([CurrencyCode]),
    CONSTRAINT [CK_PaymentTransaction_Rule1] CHECK (TransactionTypeCode IN ('authorize','capture','failure','void','refund','dispute')),
    CONSTRAINT [CK_PaymentTransaction_Rule2] CHECK (StatusCode IN ('pending','succeeded','failed')),
    CONSTRAINT [CK_PaymentTransaction_Rule3] CHECK (Amount >= 0)
);
