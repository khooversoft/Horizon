CREATE TABLE [AppDbo].[PaymentMethod]
(
    [RowId] bigint IDENTITY(1,1) NOT NULL,
    [PaymentMethodId] nvarchar(50) NOT NULL,
    [CustomerRowId] bigint NOT NULL,
    [ProviderCode] nvarchar(50) NOT NULL,
    [ProviderCustomerId] nvarchar(200) NULL,
    [ProviderPaymentMethodId] nvarchar(200) NOT NULL,
    [MethodTypeCode] varchar(30) NOT NULL,
    [DisplayBrand] nvarchar(50) NULL,
    [DisplayLastFour] char(4) NULL,
    [ExpirationMonth] tinyint NULL,
    [ExpirationYear] smallint NULL,
    [IsDefault] bit NOT NULL CONSTRAINT [DF_PaymentMethod_IsDefault] DEFAULT (0),
    [StatusCode] varchar(20) NOT NULL CONSTRAINT [DF_PaymentMethod_StatusCode] DEFAULT ('active'),
    [CreatedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_PaymentMethod_CreatedUtc] DEFAULT (SYSUTCDATETIME()),
    [ModifiedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_PaymentMethod_ModifiedUtc] DEFAULT (SYSUTCDATETIME()),
    [RowVersion] rowversion NOT NULL,
    [JsonData] varchar(max) NULL,
    CONSTRAINT [PK_PaymentMethod] PRIMARY KEY CLUSTERED ([RowId]),
    CONSTRAINT [UQ_PaymentMethod_PaymentMethodId] UNIQUE NONCLUSTERED ([PaymentMethodId]),
    CONSTRAINT [CK_PaymentMethod_BusinessId] CHECK (LEN(TRIM([PaymentMethodId])) > 0),
    CONSTRAINT [CK_PaymentMethod_JsonData] CHECK ([JsonData] IS NULL OR ISJSON([JsonData]) = 1),
    CONSTRAINT [FK_PaymentMethod_CustomerRowId] FOREIGN KEY ([CustomerRowId]) REFERENCES [AppDbo].[Customer] ([RowId]),
    CONSTRAINT [CK_PaymentMethod_Rule1] CHECK (MethodTypeCode IN ('card','bank','wallet')),
    CONSTRAINT [CK_PaymentMethod_Rule2] CHECK (StatusCode IN ('active','expired','detached')),
    CONSTRAINT [CK_PaymentMethod_Rule3] CHECK (ExpirationMonth IS NULL OR ExpirationMonth BETWEEN 1 AND 12),
    CONSTRAINT [CK_PaymentMethod_Rule4] CHECK (DisplayLastFour IS NULL OR DisplayLastFour NOT LIKE '%[^0-9]%')
);
