CREATE TABLE [AppDbo].[ProductVariant]
(
    [RowId] bigint IDENTITY(1,1) NOT NULL,
    [ProductVariantId] nvarchar(50) NOT NULL,
    [ProductRowId] bigint NOT NULL,
    [Sku] nvarchar(75) NOT NULL,
    [Name] nvarchar(200) NOT NULL,
    [UnitPrice] decimal(19,4) NOT NULL,
    [CurrencyCode] char(3) NOT NULL,
    [WeightValue] decimal(12,4) NULL,
    [WeightUnitCode] nvarchar(20) NULL,
    [FulfillmentProviderCode] nvarchar(50) NULL,
    [ProviderSku] nvarchar(100) NULL,
    [StatusCode] varchar(20) NOT NULL CONSTRAINT [DF_ProductVariant_StatusCode] DEFAULT ('active'),
    [SubscriptionEligible] bit NOT NULL CONSTRAINT [DF_ProductVariant_SubscriptionEligible] DEFAULT (0),
    [CreatedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_ProductVariant_CreatedUtc] DEFAULT (SYSUTCDATETIME()),
    [ModifiedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_ProductVariant_ModifiedUtc] DEFAULT (SYSUTCDATETIME()),
    [RowVersion] rowversion NOT NULL,
    [JsonData] varchar(max) NULL,
    CONSTRAINT [PK_ProductVariant] PRIMARY KEY CLUSTERED ([RowId]),
    CONSTRAINT [UQ_ProductVariant_ProductVariantId] UNIQUE NONCLUSTERED ([ProductVariantId]),
    CONSTRAINT [CK_ProductVariant_BusinessId] CHECK (LEN(TRIM([ProductVariantId])) > 0),
    CONSTRAINT [CK_ProductVariant_JsonData] CHECK ([JsonData] IS NULL OR ISJSON([JsonData]) = 1),
    CONSTRAINT [FK_ProductVariant_ProductRowId] FOREIGN KEY ([ProductRowId]) REFERENCES [AppDbo].[Product] ([RowId]),
    CONSTRAINT [FK_ProductVariant_CurrencyCode] FOREIGN KEY ([CurrencyCode]) REFERENCES [AppDbo].[Currency] ([CurrencyCode]),
    CONSTRAINT [FK_ProductVariant_WeightUnitCode] FOREIGN KEY ([WeightUnitCode]) REFERENCES [AppDbo].[UnitOfMeasure] ([UnitCode]),
    CONSTRAINT [CK_ProductVariant_Rule1] CHECK (UnitPrice >= 0),
    CONSTRAINT [CK_ProductVariant_Rule2] CHECK (WeightValue IS NULL OR WeightValue >= 0),
    CONSTRAINT [CK_ProductVariant_Rule3] CHECK (StatusCode IN ('active','inactive','retired'))
);
