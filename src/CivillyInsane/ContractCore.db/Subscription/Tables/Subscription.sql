CREATE TABLE [AppDbo].[Subscription]
(
    [RowId] bigint IDENTITY(1,1) NOT NULL,
    [SubscriptionId] nvarchar(50) NOT NULL,
    [SiteRowId] bigint NOT NULL,
    [CustomerRowId] bigint NOT NULL,
    [ShippingAddressRowId] bigint NOT NULL,
    [PaymentMethodRowId] bigint NOT NULL,
    [FrequencyCode] varchar(30) NOT NULL,
    [IntervalCount] smallint NOT NULL,
    [IntervalUnitCode] varchar(20) NOT NULL,
    [StatusCode] varchar(25) NOT NULL CONSTRAINT [DF_Subscription_StatusCode] DEFAULT ('draft'),
    [NextProcessUtc] datetime2(3) NULL,
    [LastProcessUtc] datetime2(3) NULL,
    [FailureCount] int NOT NULL CONSTRAINT [DF_Subscription_FailureCount] DEFAULT (0),
    [DiscountPercent] decimal(9,4) NOT NULL CONSTRAINT [DF_Subscription_DiscountPercent] DEFAULT (0),
    [LeaseToken] uniqueidentifier NULL,
    [LeaseExpiresUtc] datetime2(3) NULL,
    [RetryAfterUtc] datetime2(3) NULL,
    [CreatedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_Subscription_CreatedUtc] DEFAULT (SYSUTCDATETIME()),
    [ModifiedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_Subscription_ModifiedUtc] DEFAULT (SYSUTCDATETIME()),
    [RowVersion] rowversion NOT NULL,
    [JsonData] varchar(max) NULL,
    CONSTRAINT [PK_Subscription] PRIMARY KEY CLUSTERED ([RowId]),
    CONSTRAINT [UQ_Subscription_SubscriptionId] UNIQUE NONCLUSTERED ([SubscriptionId]),
    CONSTRAINT [CK_Subscription_BusinessId] CHECK (LEN(TRIM([SubscriptionId])) > 0),
    CONSTRAINT [CK_Subscription_JsonData] CHECK ([JsonData] IS NULL OR ISJSON([JsonData]) = 1),
    CONSTRAINT [FK_Subscription_SiteRowId] FOREIGN KEY ([SiteRowId]) REFERENCES [AppDbo].[Site] ([RowId]),
    CONSTRAINT [FK_Subscription_CustomerRowId] FOREIGN KEY ([CustomerRowId]) REFERENCES [AppDbo].[Customer] ([RowId]),
    CONSTRAINT [FK_Subscription_ShippingAddressRowId] FOREIGN KEY ([ShippingAddressRowId]) REFERENCES [AppDbo].[CustomerAddress] ([RowId]),
    CONSTRAINT [FK_Subscription_PaymentMethodRowId] FOREIGN KEY ([PaymentMethodRowId]) REFERENCES [AppDbo].[PaymentMethod] ([RowId]),
    CONSTRAINT [CK_Subscription_Rule1] CHECK (IntervalCount > 0),
    CONSTRAINT [CK_Subscription_Rule2] CHECK (IntervalUnitCode IN ('day','week','month')),
    CONSTRAINT [CK_Subscription_Rule3] CHECK (StatusCode IN ('draft','active','paused','payment-failed','cancelled','completed')),
    CONSTRAINT [CK_Subscription_Rule4] CHECK (FailureCount >= 0),
    CONSTRAINT [CK_Subscription_Rule5] CHECK (DiscountPercent BETWEEN 0 AND 100),
    CONSTRAINT [CK_Subscription_Rule6] CHECK (StatusCode NOT IN ('active','payment-failed') OR NextProcessUtc IS NOT NULL),
    CONSTRAINT [FK_Subscription_CustomerAddress_Ownership] FOREIGN KEY (ShippingAddressRowId,CustomerRowId) REFERENCES [AppDbo].[CustomerAddress] (RowId,CustomerRowId),
    CONSTRAINT [FK_Subscription_PaymentMethod_Ownership] FOREIGN KEY (PaymentMethodRowId,CustomerRowId) REFERENCES [AppDbo].[PaymentMethod] (RowId,CustomerRowId)
);
