CREATE TABLE [AppDbo].[OutboxMessage]
(
    [RowId] bigint IDENTITY(1,1) NOT NULL,
    [OutboxMessageId] nvarchar(50) NOT NULL,
    [MessageTypeCode] nvarchar(100) NOT NULL,
    [AggregateTypeCode] nvarchar(50) NOT NULL,
    [AggregateId] nvarchar(320) NOT NULL,
    [PayloadJson] varchar(max) NOT NULL,
    [StatusCode] varchar(20) NOT NULL CONSTRAINT [DF_OutboxMessage_StatusCode] DEFAULT ('pending'),
    [AttemptCount] int NOT NULL CONSTRAINT [DF_OutboxMessage_AttemptCount] DEFAULT (0),
    [PublishedUtc] datetime2(3) NULL,
    [LastError] nvarchar(max) NULL,
    [LeaseToken] uniqueidentifier NULL,
    [LeaseExpiresUtc] datetime2(3) NULL,
    [CreatedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_OutboxMessage_CreatedUtc] DEFAULT (SYSUTCDATETIME()),
    [ModifiedUtc] datetime2(3) NOT NULL CONSTRAINT [DF_OutboxMessage_ModifiedUtc] DEFAULT (SYSUTCDATETIME()),
    [RowVersion] rowversion NOT NULL,
    [JsonData] varchar(max) NULL,
    CONSTRAINT [PK_OutboxMessage] PRIMARY KEY CLUSTERED ([RowId]),
    CONSTRAINT [UQ_OutboxMessage_OutboxMessageId] UNIQUE NONCLUSTERED ([OutboxMessageId]),
    CONSTRAINT [CK_OutboxMessage_BusinessId] CHECK (LEN(TRIM([OutboxMessageId])) > 0),
    CONSTRAINT [CK_OutboxMessage_JsonData] CHECK ([JsonData] IS NULL OR ISJSON([JsonData]) = 1),
    CONSTRAINT [CK_OutboxMessage_PayloadJson] CHECK ([PayloadJson] IS NULL OR ISJSON([PayloadJson]) = 1),
    CONSTRAINT [CK_OutboxMessage_Rule1] CHECK (StatusCode IN ('pending','publishing','published','failed')),
    CONSTRAINT [CK_OutboxMessage_Rule2] CHECK (AttemptCount >= 0)
);
